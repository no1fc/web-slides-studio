import JSZip from "jszip";

const points = (px) => px / 2;
const emu = (pt) => Math.round(pt * 12700);
const number = (value, fallback) => Number.isFinite(value) ? value : fallback;
function face(value) {
  const family = String(value || "맑은 고딕").trim().match(/^("[^"]*"|'[^']*'|[^,]+)/)?.[0].trim() || "맑은 고딕";
  // PptxGenJS escapes run text but interpolates fontFace directly into XML.
  return family.replace(/^["']|["']$/g, "").replaceAll("&", "&amp;").replaceAll('"', "&quot;").replaceAll("<", "&lt;").replaceAll(">", "&gt;");
}
const color = (value) => /^[\da-f]{6}$/i.test(String(value || "").replace(/^#/, ""))
  ? String(value).replace(/^#/, "").toUpperCase() : "000000";

export function canExportNativeText(element) {
  return !(element.textBox?.overflow === "clip" && element.textOverflowing);
}

/** Map the displayed document pixels to a 1920px-wide, 13 1/3 inch slide. */
export function pptxText(element, objectName) {
  const scale = Math.max(0, Math.min(1, number(element.fontScale, 1)));
  const metricsScale = Math.max(0.01, number(element.textMetricsScale, 1));
  const fontSize = (value) => points(Math.max(6, number(value, number(element.fontSize, 32)) * scale));
  const paragraphs = element.richText?.paragraphs || String(element.text || "").split(/\r?\n/).map(text => ({ runs: [{ text }] }));
  const runs = [];
  const paragraphXml = [];
  const paragraphSizes = [];
  const counters = [];
  for (const [index, paragraph] of paragraphs.entries()) {
    const align = paragraph.align || element.align || "left";
    const indent = paragraph.indent || 0;
    const list = paragraph.list || "none";
    const sourceRuns = paragraph.runs.length ? paragraph.runs : [{ text: "" }];
    counters.length = indent + 1;
    if (list === "number") counters[indent] = (counters[indent] || 0) + 1;
    else counters[indent] = 0;
    const lineHeight = number(paragraph.lineHeight, number(element.lineHeight, 1.2));
    const after = points(number(paragraph.spaceAfter, 0) * scale);
    const left = points((indent * 32 + (list === "none" ? 0 : 24)) * scale * metricsScale);
    const bullet = list === "number"
      ? `<a:buAutoNum type="arabicPeriod" startAt="${counters[indent]}"/>`
      : list === "bullet" ? '<a:buChar char="&#x2022;"/>' : "<a:buNone/>";
    paragraphXml.push(`<a:pPr algn="${({ left: "l", center: "ctr", right: "r", justify: "just" })[align] || "l"}" lvl="${indent}" marL="${emu(left)}" indent="${list === "none" ? 0 : -emu(12 * scale * metricsScale)}"><a:lnSpc><a:spcPct val="${Math.round(lineHeight * 100000)}"/></a:lnSpc><a:spcAft><a:spcPts val="${Math.round(after * 100)}"/></a:spcAft>${bullet}</a:pPr>`);
    paragraphSizes.push(Math.max(...sourceRuns.map(run => fontSize(run.fontSize))));
    for (const [runIndex, run] of sourceRuns.entries()) {
      const lines = run.text.split(/\r\n?|\n/);
      for (const [lineIndex, text] of lines.entries()) runs.push({ text, options: {
        fontFace: face(run.fontFamily || element.fontFamily),
        fontSize: fontSize(run.fontSize),
        color: color(run.color || element.color),
        bold: run.bold ?? element.bold ?? false,
        italic: run.italic ?? element.italic ?? false,
        underline: run.underline ?? element.underline ?? false,
        align,
        softBreakBefore: lineIndex > 0,
        breakLine: lineIndex === lines.length - 1 && runIndex === sourceRuns.length - 1 && index < paragraphs.length - 1,
      } });
    }
  }
  const padding = element.padding || {};
  return {
    runs, paragraphXml, paragraphSizes,
    options: {
      objectName,
      x: element.x / 144, y: element.y / 144, w: element.w / 144, h: element.h / 144,
      fontSize: fontSize(element.fontSize),
      // PptxGenJS 4.0.1 uses left/right/bottom/top for text shapes (unlike its docs).
      margin: [padding.left, padding.right, padding.bottom, padding.top].map(value => points(number(value, 0))),
      valign: element.textBox?.vertical || "top",
      fit: "none", rotate: element.rotate || 0, lang: "ko-KR",
    },
  };
}

/**
 * PptxGenJS 4 emits one pPr per run and forces non-list marL to zero.
 * Replace only our named native shapes' paragraph properties; keep text and all
 * character properties generated by the library. This also sizes empty lines.
 */
export async function finalizeTextPptx(buffer, slides) {
  if (!slides.some(shapes => shapes.length)) return buffer;
  const zip = await JSZip.loadAsync(buffer);
  for (const [index, shapes] of slides.entries()) {
    if (!shapes.length) continue;
    const path = `ppt/slides/slide${index + 1}.xml`;
    const models = new Map(shapes.map(shape => [shape.options.objectName, shape]));
    const xml = await zip.file(path).async("string");
    zip.file(path, xml.replace(/<p:sp>[\s\S]*?<\/p:sp>/g, shapeXml => {
      const name = shapeXml.match(/<p:cNvPr\b[^>]*\bname="([^"]*)"/)?.[1];
      const model = models.get(name);
      if (!model) return shapeXml;
      let paragraphIndex = 0;
      return shapeXml.replace(/<a:p>[\s\S]*?<\/a:p>/g, paragraph => {
        const current = paragraphIndex++;
        if (!model.paragraphXml[current]) throw new Error("PPTX 문단 구조가 저장된 텍스트와 일치하지 않습니다.");
        const content = paragraph
          .replace(/<a:pPr\b[^>]*(?:\/>|>[\s\S]*?<\/a:pPr>)/g, "")
          .replace(/<a:endParaRPr\b([^>]*?)\/>/, (_, attributes) => `<a:endParaRPr${attributes.replace(/\s+sz="[^"]*"/, "")} sz="${Math.round(model.paragraphSizes[current] * 100)}"/>`);
        return content.replace("<a:p>", "<a:p>" + model.paragraphXml[current]);
      });
    }));
  }
  return zip.generateAsync({ type: "nodebuffer", compression: "DEFLATE" });
}
